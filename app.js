let currentLang = localStorage.getItem('portfolio_lang') || 'fr';
let currentTheme = localStorage.getItem('portfolio_theme') || 'dark';

const langBtn = document.getElementById('langBtn');
const themeBtn = document.getElementById('themeBtn');
const burgerBtn = document.getElementById('burgerBtn');
const navLinks = document.getElementById('navLinks');
const contactForm = document.getElementById('contactForm');
const formFeedback = document.getElementById('formFeedback');

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('portfolio_lang', lang);
  document.documentElement.lang = lang;
  langBtn.textContent = lang === 'fr' ? 'EN' : 'FR';

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang][key]) el.setAttribute('placeholder', translations[lang][key]);
  });
}

function applyTheme(theme) {
  currentTheme = theme;
  localStorage.setItem('portfolio_theme', theme);
  document.documentElement.setAttribute('data-theme', theme);
  themeBtn.textContent = theme === 'dark' ? '☀️ Clair' : '🌙 Sombre';
}

function openProjectModal(id) {
  const data = projectDetails[id];
  if (!data) return;
  document.getElementById('modalTag').textContent = data.tag[currentLang];
  document.getElementById('modalTitle').textContent = data.title[currentLang];
  document.getElementById('modalBody').innerHTML = data.body[currentLang];
  document.getElementById('projectModal').hidden = false;
}

function closeProjectModal() {
  document.getElementById('projectModal').hidden = true;
}

window.openProjectModal = openProjectModal;
window.closeProjectModal = closeProjectModal;

langBtn.addEventListener('click', () => applyLanguage(currentLang === 'fr' ? 'en' : 'fr'));
themeBtn.addEventListener('click', () => applyTheme(currentTheme === 'dark' ? 'light' : 'dark'));
burgerBtn.addEventListener('click', () => navLinks.classList.toggle('open'));

contactForm.addEventListener('submit', (e) => {
  e.preventDefault();
  const name = document.getElementById('nameInput').value.trim();
  const email = document.getElementById('emailInput').value.trim();
  const msg = document.getElementById('msgInput').value.trim();
  const subject = encodeURIComponent(`Contact Portfolio — ${name}`);
  const body = encodeURIComponent(`Nom / Entreprise : ${name}\nEmail : ${email}\n\n${msg}`);
  window.location.href = `mailto:fakhabib@live.fr?subject=${subject}&body=${body}`;
  formFeedback.textContent = translations[currentLang].form_ok;
  contactForm.reset();
});

// Scroll reveal
const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) entry.target.classList.add('visible');
  });
}, { threshold: 0.08 });
document.querySelectorAll('.reveal').forEach((el) => observer.observe(el));

// Lightbox pour agrandir les images au clic
function openLightbox(src, alt) {
  const lb = document.getElementById('imageLightbox');
  document.getElementById('lightboxImg').src = src;
  document.getElementById('lightboxImg').alt = alt || '';
  document.getElementById('lightboxCaption').textContent = alt || '';
  lb.hidden = false;
}

function closeLightbox() {
  document.getElementById('imageLightbox').hidden = true;
}

window.openLightbox = openLightbox;
window.closeLightbox = closeLightbox;

document.querySelectorAll('main img, .modal-photos img').forEach((img) => {
  img.classList.add('zoomable-img');
  img.addEventListener('click', () => openLightbox(img.src, img.alt));
});

document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') {
    closeLightbox();
    closeProjectModal();
  }
});

document.getElementById('year').textContent = new Date().getFullYear();
applyLanguage(currentLang);
applyTheme(currentTheme);
